begin;

create table if not exists public.supervisor_workload_reports (
  id bigint generated by default as identity primary key,
  supervisor_user_id uuid not null references auth.users(id) on delete cascade,
  semester_code text not null check (length(trim(semester_code)) between 3 and 40),
  supervisor_note text,
  report_status text not null default 'draft'
    check (report_status in ('draft','submitted','approved','returned')),
  submitted_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  review_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (supervisor_user_id, semester_code)
);

create table if not exists public.supervisor_training_visits (
  id bigint generated by default as identity primary key,
  supervisor_user_id uuid not null references auth.users(id) on delete cascade,
  student_user_id uuid not null references auth.users(id) on delete cascade,
  semester_code text not null check (length(trim(semester_code)) between 3 and 40),
  visit_number smallint not null check (visit_number between 1 and 4),
  visit_date date,
  visit_type text not null default 'ميدانية',
  visit_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_user_id, semester_code, visit_number)
);

create index if not exists idx_workload_reports_semester_status
  on public.supervisor_workload_reports(semester_code, report_status);
create index if not exists idx_workload_reports_supervisor
  on public.supervisor_workload_reports(supervisor_user_id);
create index if not exists idx_supervisor_visits_supervisor_semester
  on public.supervisor_training_visits(supervisor_user_id, semester_code);
create index if not exists idx_supervisor_visits_student_semester
  on public.supervisor_training_visits(student_user_id, semester_code);

alter table public.supervisor_workload_reports enable row level security;
alter table public.supervisor_training_visits enable row level security;

grant select on public.supervisor_workload_reports to authenticated;
grant select on public.supervisor_training_visits to authenticated;
revoke insert, update, delete on public.supervisor_workload_reports from authenticated;
revoke insert, update, delete on public.supervisor_training_visits from authenticated;

drop policy if exists "supervisor or department reads workload reports" on public.supervisor_workload_reports;
create policy "supervisor or department reads workload reports"
on public.supervisor_workload_reports for select to authenticated
using (
  supervisor_user_id = (select auth.uid())
  or public.has_staff_role(array['admin','department_head'])
);

drop policy if exists "supervisor or department reads training visits" on public.supervisor_training_visits;
create policy "supervisor or department reads training visits"
on public.supervisor_training_visits for select to authenticated
using (
  supervisor_user_id = (select auth.uid())
  or public.has_staff_role(array['admin','department_head'])
);

-- Supervisor records one of the four planned visits for a student assigned to them.
-- Upsert is allowed only while the report is draft/returned; approved reports are locked.
create or replace function public.save_supervisor_training_visit(
  p_student_user_id uuid,
  p_semester_code text,
  p_visit_number integer,
  p_visit_date date,
  p_visit_type text default 'ميدانية',
  p_visit_notes text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_supervisor uuid := (select auth.uid());
  v_report_status text;
  v_visit_id bigint;
begin
  if not public.has_staff_role(array['supervisor']) then
    raise exception 'Only an assigned supervisor may record visits';
  end if;
  if p_semester_code is null or length(trim(p_semester_code)) not between 3 and 40 then
    raise exception 'Enter the semester label, e.g. 2026-1';
  end if;
  if p_visit_number is null or p_visit_number not between 1 and 4 then
    raise exception 'Visit number must be between 1 and 4';
  end if;
  if p_visit_date is null then
    raise exception 'Visit date is required';
  end if;
  if not exists (
    select 1 from public.supervisor_assignments sa
    where sa.supervisor_user_id = v_supervisor
      and sa.student_user_id = p_student_user_id
  ) then
    raise exception 'This student is not assigned to the current supervisor';
  end if;

  insert into public.supervisor_workload_reports(supervisor_user_id, semester_code)
  values (v_supervisor, trim(p_semester_code))
  on conflict (supervisor_user_id, semester_code) do nothing;

  select wr.report_status into v_report_status
  from public.supervisor_workload_reports wr
  where wr.supervisor_user_id = v_supervisor
    and wr.semester_code = trim(p_semester_code)
  for update;

  if v_report_status not in ('draft','returned') then
    raise exception 'The workload report is already submitted or approved and is locked';
  end if;

  insert into public.supervisor_training_visits
    (supervisor_user_id, student_user_id, semester_code, visit_number, visit_date, visit_type, visit_notes)
  values
    (v_supervisor, p_student_user_id, trim(p_semester_code), p_visit_number,
     p_visit_date, coalesce(nullif(trim(p_visit_type),''),'ميدانية'), nullif(trim(p_visit_notes),''))
  on conflict (student_user_id, semester_code, visit_number)
  do update set
    supervisor_user_id = excluded.supervisor_user_id,
    visit_date = excluded.visit_date,
    visit_type = excluded.visit_type,
    visit_notes = excluded.visit_notes,
    updated_at = now()
  where public.supervisor_training_visits.supervisor_user_id = v_supervisor
  returning id into v_visit_id;

  if v_visit_id is null then
    raise exception 'This visit number is already recorded by another supervisor';
  end if;
  update public.supervisor_workload_reports
  set updated_at = now()
  where supervisor_user_id = v_supervisor and semester_code = trim(p_semester_code);
  return v_visit_id;
end;
$$;

create or replace function public.submit_supervisor_workload(
  p_semester_code text,
  p_supervisor_note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_supervisor uuid := (select auth.uid());
  v_status text;
begin
  if not public.has_staff_role(array['supervisor']) then
    raise exception 'Only a supervisor may submit a workload report';
  end if;
  if p_semester_code is null or length(trim(p_semester_code)) not between 3 and 40 then
    raise exception 'Enter the semester label, e.g. 2026-1';
  end if;
  if not exists (
    select 1 from public.supervisor_assignments sa
    where sa.supervisor_user_id = v_supervisor
  ) then
    raise exception 'No students are assigned to this supervisor';
  end if;

  insert into public.supervisor_workload_reports(supervisor_user_id, semester_code)
  values (v_supervisor, trim(p_semester_code))
  on conflict (supervisor_user_id, semester_code) do nothing;

  select report_status into v_status
  from public.supervisor_workload_reports
  where supervisor_user_id = v_supervisor
    and semester_code = trim(p_semester_code)
  for update;

  if v_status not in ('draft','returned') then
    raise exception 'This report has already been submitted or approved';
  end if;

  update public.supervisor_workload_reports
  set supervisor_note = nullif(trim(p_supervisor_note),''),
      report_status = 'submitted',
      submitted_at = now(),
      reviewed_by = null,
      reviewed_at = null,
      review_note = null,
      updated_at = now()
  where supervisor_user_id = v_supervisor
    and semester_code = trim(p_semester_code);
end;
$$;

create or replace function public.review_supervisor_workload(
  p_report_id bigint,
  p_decision text,
  p_review_note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.has_staff_role(array['admin','department_head']) then
    raise exception 'Only department head or admin may review workload reports';
  end if;
  if p_decision not in ('approved','returned') then
    raise exception 'Decision must be approved or returned';
  end if;
  if p_decision = 'returned' and (p_review_note is null or length(trim(p_review_note)) = 0) then
    raise exception 'A reason is required when returning a report';
  end if;

  update public.supervisor_workload_reports
  set report_status = p_decision,
      reviewed_by = (select auth.uid()),
      reviewed_at = now(),
      review_note = nullif(trim(p_review_note),''),
      updated_at = now()
  where id = p_report_id and report_status = 'submitted';

  if not found then
    raise exception 'Submitted workload report not found or already reviewed';
  end if;
end;
$$;

