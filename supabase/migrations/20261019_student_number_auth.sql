-- Al-Aqsa Field Training student login schema preparation.
-- Additive only; review against live schema and test in staging first.
begin;
create table if not exists public.public_supervisors (
  id bigint generated by default as identity primary key,
  name text not null, region text not null, category text not null default 'الجميع',
  specialty text not null, phone text, is_active boolean not null default true
);
alter table public.public_supervisors add column if not exists phone text;
alter table public.public_supervisors add column if not exists is_active boolean not null default true;
alter table public.public_supervisors add column if not exists user_id uuid references auth.users(id) on delete set null;
create unique index if not exists public_supervisors_user_id_unique_idx on public.public_supervisors (user_id) where user_id is not null;
alter table public.public_supervisors enable row level security;
revoke select on table public.public_supervisors from anon, authenticated;
grant select (id, name, region, category, specialty, is_active) on public.public_supervisors to anon, authenticated;
grant select (phone) on public.public_supervisors to authenticated; -- contact numbers are available after sign-in only
drop policy if exists "public reads active supervisors for signup" on public.public_supervisors;
create policy "public reads active supervisors for signup" on public.public_supervisors
for select to anon, authenticated using (is_active = true);
-- The production project already has this table and 414 records. IF NOT EXISTS preserves its
-- existing column names (including added_by) and all rows; do not replace or reload this table.
create table if not exists public.eligible_student_roster (
  university_number text primary key,
  full_name text not null,
  gender text not null check (gender in ('male','female')),
  specialty_id bigint references public.specialties(id) on delete set null,
  is_active boolean not null default true, notes text,
  imported_by uuid references auth.users(id) on delete set null,
  imported_at timestamptz not null default now(),
  constraint roster_number_prefix_matches_gender check (
    (gender='male' and university_number like '122%') or
    (gender='female' and university_number like '222%')
  )
);
alter table public.eligible_student_roster add column if not exists is_active boolean not null default true;
alter table public.eligible_student_roster enable row level security;
revoke all on table public.eligible_student_roster from anon, authenticated;
alter table public.student_profiles add column if not exists student_area text;
alter table public.student_profiles add column if not exists supervisor_name text;
alter table public.student_profiles add column if not exists supervisor_phone text;
-- student_profiles already has a UNIQUE constraint on university_number; no duplicate index needed.
create table if not exists public.student_password_reset_requests (
 id bigint generated by default as identity primary key,
 university_number text not null, phone text not null,
 status text not null default 'pending' check (status in ('pending','approved','rejected','closed')),
 requested_at timestamptz not null default now(), resolved_at timestamptz,
 resolved_by uuid references auth.users(id) on delete set null, resolution_note text
);
alter table public.student_password_reset_requests enable row level security;
revoke all on table public.student_password_reset_requests from anon, authenticated;
create index if not exists student_password_reset_requests_status_date_idx on public.student_password_reset_requests (status, requested_at desc);
create index if not exists student_password_reset_requests_number_idx on public.student_password_reset_requests (university_number);
-- Existing constraint student_profiles_university_number_key already enforces unique student numbers.
commit;
